def _get_extract_dir():
    """
    Get the directory where packages are extracted.

    Uses %LOCALAPPDATA%/MCAEditor-Maya2026-py3.11 on Windows.
    Both the Maya year AND the Python major.minor version are
    included so each Maya version gets its own isolated cache —
    even if two versions share the same Python ABI.

    :rtype: str
    """
    # Include both Maya version and Python version for full isolation.
    py_ver = "{}.{}".format(sys.version_info.major, sys.version_info.minor)
    dir_name = "{}-Maya{}-py{}".format(_EXTRACT_DIR_NAME, _MAYA_VERSION, py_ver)
    local = os.environ.get("LOCALAPPDATA")
    if local:
        return os.path.join(local, dir_name)
    return os.path.join(os.path.expanduser("~"), dir_name)


def _needs_extraction(extract_dir):
    """
    Check if extraction is needed (first run, version mismatch, or build hash mismatch).

    Compares both version and build hash so that same-version rebuilds
    (e.g. bug fix at v0.3.9 without bumping version) still trigger
    re-extraction instead of silently running stale cached code.

    :param str extract_dir: Target extraction directory.
    :rtype: bool
    """
    version_file = os.path.join(extract_dir, _VERSION_FILENAME)
    if not os.path.isfile(version_file):
        return True
    try:
        with open(version_file, "r") as f:
            installed = f.read().strip()
        # The stamp is "version:hash" — both must match.
        expected = "{}:{}".format(_VERSION, _BUILD_HASH)
        return installed != expected
    except (IOError, OSError):
        return True


def _extract_payload(extract_dir):
    """
    Decode the base64 payload and extract all files.

    Extracts into a temporary directory first, then moves into place.
    This prevents a partial extraction if Maya crashes mid-extract.

    :param str extract_dir: Target extraction directory.
    """
    import shutil
    import tempfile

    _logger.info("MCA Editor %s — extracting to %s", _VERSION, extract_dir)

    # Decode
    payload_bytes = base64.b64decode(_PAYLOAD)

    # Extract to temp dir first (atomic-ish swap)
    temp_dir = tempfile.mkdtemp(prefix="mca_extract_")
    try:
        with zipfile.ZipFile(io.BytesIO(payload_bytes), "r") as zf:
            zf.extractall(temp_dir)

        # Write version+hash marker to temp dir so _needs_extraction()
        # can detect both version bumps AND same-version rebuilds.
        version_file = os.path.join(temp_dir, _VERSION_FILENAME)
        with open(version_file, "w") as f:
            f.write("{}:{}".format(_VERSION, _BUILD_HASH))

        # Remove old install if it exists
        if os.path.isdir(extract_dir):
            shutil.rmtree(extract_dir)

        # Move temp dir into place
        shutil.move(temp_dir, extract_dir)

        _logger.info("MCA Editor %s — extraction complete", _VERSION)

    except Exception:
        # Clean up temp dir on failure
        if os.path.isdir(temp_dir):
            shutil.rmtree(temp_dir, ignore_errors=True)
        raise


def _ensure_extracted():
    """
    Ensure packages are extracted and on sys.path.

    :rtype: str
    :return: The extraction directory path.
    """
    extract_dir = _get_extract_dir()

    if _needs_extraction(extract_dir):
        _extract_payload(extract_dir)

    if extract_dir not in sys.path:
        sys.path.insert(0, extract_dir)

    return extract_dir


