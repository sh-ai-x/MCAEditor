def create_payload_zip(dist_dir):
    """
    Create an in-memory zip file from the distribution directory.

    Includes all files except install/uninstall scripts and the zip
    itself.  Preserves directory structure.

    :param str dist_dir: Path to the compiled distribution directory.
    :rtype: tuple(bytes, int)
    :return: (zip_bytes, file_count)
    """
    skip_files = {
        "install.py", "install_maya.py",
        "uninstall.py", "uninstall_maya.py",
    }

    buffer = io.BytesIO()
    file_count = 0

    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, dirs, files in os.walk(dist_dir):
            # Skip __pycache__ directories — sourceless .pyc files are
            # placed directly in package dirs, not in __pycache__/.
            dirs[:] = [d for d in dirs if d != "__pycache__"]

            for filename in files:
                if filename in skip_files:
                    continue

                filepath = os.path.join(root, filename)
                arcname = os.path.relpath(filepath, dist_dir)

                zf.write(filepath, arcname)
                file_count += 1

    return buffer.getvalue(), file_count


def format_payload_string(b64_data, line_width=76):
    """
    Format a base64 string as a series of concatenated Python string
    literals, suitable for embedding in source code.

    Each line is a quoted string, and lines are concatenated with
    implicit string joining.

    :param str b64_data: The base64-encoded string.
    :param int line_width: Maximum characters per line.
    :rtype: str
    """
    lines = []
    for i in range(0, len(b64_data), line_width):
        chunk = b64_data[i:i + line_width]
        lines.append('    "{}"'.format(chunk))
    return "\n".join(lines)


def pack(dist_dir, output_path, maya_version="2025"):
    """
    Pack the distribution directory into a single .py file.

    :param str dist_dir: Path to the compiled distribution directory.
    :param str output_path: Path for the output .py file.
    :param str maya_version: Target Maya year (e.g. "2025", "2026").
        Embedded in the output so each Maya version extracts to its
        own cache directory.
    :return: Dict with build stats.
    :rtype: dict
    """
    print("Packing MCA Editor v{} into single file...".format(VERSION))
    print("  Source: {}".format(dist_dir))
    print("  Output: {}".format(output_path))

    # --- Create the zip payload ---
    print("  Creating zip payload...")
    zip_bytes, file_count = create_payload_zip(dist_dir)
    print("    {} files, {:.1f} KB compressed".format(
        file_count, len(zip_bytes) / 1024
    ))

    # --- Encode as base64 ---
    b64_data = base64.b64encode(zip_bytes).decode("ascii")
    print("    {:.1f} KB base64".format(len(b64_data) / 1024))

    # --- Format as Python string literal ---
    payload_str = format_payload_string(b64_data)

    # --- Fill the template ---
    build_date = datetime.date.today().isoformat()

    # Compute a short hash of the zip payload so same-version rebuilds
    # still trigger re-extraction (prevents stale cache bugs).
    import hashlib
    build_hash = hashlib.sha256(zip_bytes).hexdigest()[:12]
    print("  Build hash: {}".format(build_hash))

    output = TEMPLATE
    output = output.replace("__MCA_VERSION__", VERSION)
    output = output.replace("__MCA_BUILD_HASH__", build_hash)
    output = output.replace("__MCA_BUILD_YEAR__", str(datetime.date.today().year))
    output = output.replace("__MCA_MAYA_VERSION__", maya_version)
    output = output.replace("__MCA_PAYLOAD__", payload_str)
    output = output.replace("__MCA_BUILD_DATE__", build_date)
    output = output.replace("__MCA_FILE_COUNT__", str(file_count))

    # --- Write ---
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(output)

    output_size = os.path.getsize(output_path)
    print()
    print("  Output: {} ({:.1f} MB)".format(output_path, output_size / (1024 * 1024)))
    print("  Version: {}".format(VERSION))
    print("  Files packed: {}".format(file_count))
    print("  Build date: {}".format(build_date))
    print()
    print("Done!  Distribute mcaEditor.py to users.")

    return {
        "version": VERSION,
        "file_count": file_count,
        "zip_size": len(zip_bytes),
        "b64_size": len(b64_data),
        "output_size": output_size,
        "output_path": output_path,
        "build_date": build_date,
    }


