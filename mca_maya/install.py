"""
MCA Maya - Installer Script.

Copies the MCA Editor plugin file and module definition (.mod) into
Maya's user directories so the plugin appears in Maya's Plug-in Manager.

Supports Maya 2024, 2025, and 2026. Creates:
    - A ``.mod`` file in ``<maya_app_dir>/modules/``
    - A plugin stub in ``<maya_app_dir>/<version>/plug-ins/``

Usage:
    python -m mca_maya.install
    # or via the mcaeditor-install-maya CLI entry point

Dependencies:
    - No Maya dependency — runs outside Maya's interpreter
"""

import os
import sys
import shutil
import logging

from mca_core import __version__

# Module-level logger.
logger = logging.getLogger(__name__)

# The .mod file content template. Maya reads this on startup to find
# our package. The path placeholder is replaced with the actual install
# location of the MCA Editor package.
MOD_TEMPLATE = """+ MCAEditor {version} {package_root}
PYTHONPATH += {package_root}
"""

# The plugin stub that goes into Maya's plug-ins directory.
# It simply imports and delegates to the real plugin_main module.
PLUGIN_STUB = '''"""
MCA Editor - Maya Plugin Stub.

Auto-generated by mca_maya.install. This file lives in Maya's plug-ins
directory and delegates to the real plugin module in the MCA Editor package.
"""

import sys
import os

# Ensure the MCA Editor package root is on sys.path.
_PACKAGE_ROOT = r"{package_root}"
if _PACKAGE_ROOT not in sys.path:
    sys.path.insert(0, _PACKAGE_ROOT)

# Maya API 2.0 flag — must be set before Maya imports plugin functions.
maya_useNewAPI = True

# Delegate to the real plugin module.
from mca_maya.plugin_main import initializePlugin, uninitializePlugin
'''


# --- Helper Functions -------------------------------------------------------

def _get_maya_app_dir():
    """
    Find Maya's application directory.

    On Windows: ``C:/Users/<user>/Documents/maya``
    On macOS: ``~/Library/Preferences/Autodesk/maya``
    On Linux: ``~/maya``

    :return: Path to Maya's application directory.
    :rtype: str
    :raises RuntimeError: If no Maya directory is found.
    """
    if sys.platform == "win32":
        docs = os.path.join(os.path.expanduser("~"), "Documents")
        maya_dir = os.path.join(docs, "maya")
    elif sys.platform == "darwin":
        maya_dir = os.path.join(
            os.path.expanduser("~"), "Library", "Preferences", "Autodesk", "maya"
        )
    else:
        # Linux.
        maya_dir = os.path.join(os.path.expanduser("~"), "maya")

    if not os.path.isdir(maya_dir):
        raise RuntimeError(
            "Maya application directory not found: {}\n"
            "Is Maya installed?".format(maya_dir)
        )

    return maya_dir


def _get_package_root():
    """
    Get the root directory of the MCA Editor package.

    This is the parent of the ``mca_maya`` directory (i.e., the project root
    or the site-packages directory if pip-installed).

    :return: Absolute path to the package root.
    :rtype: str
    """
    # This file is mca_maya/install.py, so go up one level.
    return os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _detect_maya_versions(maya_dir):
    """
    Detect installed Maya versions by looking for version directories.

    :param str maya_dir: Maya's application directory.
    :return: List of version strings (e.g., ['2024', '2025', '2026']).
    :rtype: list
    """
    versions = []
    for entry in os.listdir(maya_dir):
        # Maya version directories are numeric (2024, 2025, etc.).
        if entry.isdigit() and int(entry) >= 2020:
            full = os.path.join(maya_dir, entry)
            if os.path.isdir(full):
                versions.append(entry)
    versions.sort()
    return versions


# --- Main Install Function --------------------------------------------------

def install():
    """
    Install MCA Editor into Maya's module/plugin directories.

    Creates:
        1. A ``.mod`` file in ``<maya_dir>/modules/`` so Maya can find
           the MCA Editor Python packages on its PYTHONPATH.
        2. A plugin stub in ``<maya_dir>/<version>/plug-ins/`` for each
           detected Maya version, so the plugin shows up in Plug-in Manager.
    """
    maya_dir = _get_maya_app_dir()
    package_root = _get_package_root()

    print("MCA Editor Installer")
    print("=" * 50)
    print("Maya app dir : {}".format(maya_dir))
    print("Package root : {}".format(package_root))
    print()

    # --- Step 1: Create .mod file ---
    modules_dir = os.path.join(maya_dir, "modules")
    os.makedirs(modules_dir, exist_ok=True)

    mod_path = os.path.join(modules_dir, "mcaeditor.mod")
    mod_content = MOD_TEMPLATE.format(version=__version__, package_root=package_root)

    with open(mod_path, "w", encoding="utf-8") as f:
        f.write(mod_content)
    print("Created module file: {}".format(mod_path))

    # --- Step 2: Create plugin stub for each Maya version ---
    versions = _detect_maya_versions(maya_dir)
    if not versions:
        print("\nWARNING: No Maya version directories found in {}".format(maya_dir))
        print("You may need to create the plug-ins directory manually.")
    else:
        for version in versions:
            plugins_dir = os.path.join(maya_dir, version, "plug-ins")
            os.makedirs(plugins_dir, exist_ok=True)

            stub_path = os.path.join(plugins_dir, "mca_editor_plugin.py")
            stub_content = PLUGIN_STUB.format(package_root=package_root)

            with open(stub_path, "w", encoding="utf-8") as f:
                f.write(stub_content)
            print("Created plugin stub: {}".format(stub_path))

    print()
    print("Installation complete!")
    print()
    print("Next steps:")
    print("  1. Open Maya")
    print("  2. Go to Windows > Settings/Preferences > Plug-in Manager")
    print("  3. Find 'mca_editor_plugin.py' and check 'Loaded'")
    print("  4. Check 'Auto load' to load automatically on startup")
    print("  5. Click the Script Editor button — MCA Editor should open!")


def uninstall():
    """
    Remove MCA Editor from Maya's module/plugin directories.

    Deletes the ``.mod`` file and all plugin stubs created by ``install()``.
    """
    maya_dir = _get_maya_app_dir()

    print("MCA Editor Uninstaller")
    print("=" * 50)

    # Remove .mod file.
    mod_path = os.path.join(maya_dir, "modules", "mcaeditor.mod")
    if os.path.isfile(mod_path):
        os.remove(mod_path)
        print("Removed: {}".format(mod_path))
    else:
        print("Not found (skip): {}".format(mod_path))

    # Remove plugin stubs.
    versions = _detect_maya_versions(maya_dir)
    for version in versions:
        stub_path = os.path.join(maya_dir, version, "plug-ins", "mca_editor_plugin.py")
        if os.path.isfile(stub_path):
            os.remove(stub_path)
            print("Removed: {}".format(stub_path))

    print()
    print("Uninstall complete.")


# --- CLI Entry Point --------------------------------------------------------

def main():
    """
    CLI entry point for the installer.

    Usage:
        mcaeditor-install-maya           # Install
        mcaeditor-install-maya uninstall  # Uninstall
    """
    logging.basicConfig(level=logging.INFO)

    if len(sys.argv) > 1 and sys.argv[1] == "uninstall":
        uninstall()
    else:
        install()


# Script guard for direct execution.
if __name__ == "__main__":
    main()
